import hre from "hardhat";
import fs from "fs";
import path from "path";
import { getAddress } from "viem";

// Deploys GameFactory and writes its address plus all ABIs into the web app.
async function main() {
  const signer = process.env.SCORE_SIGNER_ADDRESS;
  if (!signer) throw new Error("SCORE_SIGNER_ADDRESS missing in contracts/.env");

  const publicClient = await hre.viem.getPublicClient();
  const chainId = await publicClient.getChainId();
  const factory = await hre.viem.deployContract("GameFactory", [getAddress(signer)]);
  const block = await publicClient.getBlockNumber();
  console.log(`GameFactory deployed on chain ${chainId}: ${factory.address} (block ${block})`);

  const outDir = path.resolve(__dirname, "../../web/src/lib/contracts");
  fs.mkdirSync(outDir, { recursive: true });

  const names = ["GameFactory", "GameToken", "TreasuryVault", "SessionManager", "BondingCurve"];
  let abis = "// Generated by contracts/scripts/deploy.ts. Do not edit.\n";
  for (const n of names) {
    const art = await hre.artifacts.readArtifact(n);
    abis += `export const ${n[0].toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  }
  fs.writeFileSync(path.join(outDir, "abis.ts"), abis);

  const deployment = {
    chainId,
    gameFactory: factory.address,
    deployBlock: block.toString(),
    scoreSigner: getAddress(signer),
    deployedAt: new Date().toISOString(),
  };
  fs.writeFileSync(path.join(outDir, `deployment.${chainId}.json`), JSON.stringify(deployment, null, 2) + "\n");
  console.log(`Wrote ABIs and deployment.${chainId}.json to ${outDir}`);
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
